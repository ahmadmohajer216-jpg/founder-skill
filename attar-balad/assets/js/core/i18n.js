let lang = "fa";

export function getLang() {
  return lang;
}

export function setLang(next) {
  lang = next === "en" ? "en" : "fa";
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "fa" ? "rtl" : "ltr";
  return lang;
}

export function t(key, vars) {
  const value = dict[lang][key] ?? dict.fa[key] ?? key;
  if (!vars) return value;
  return String(value).replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name])
  );
}

/** Read a bilingual data field: {fa, en} */
export function L(field) {
  if (!field) return "";
  if (typeof field === "string") return field;
  return field[lang] ?? field.fa ?? "";
}

const numberFormat = () => new Intl.NumberFormat(lang === "fa" ? "fa-IR" : "en-US");

export function nf(n) {
  return numberFormat().format(Number(n) || 0);
}

export function money(n) {
  return `${nf(n)} ${t("common.currency")}`;
}

export function formatDate(iso) {
  try {
    return new Intl.DateTimeFormat(lang === "fa" ? "fa-IR" : "en-GB", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }).format(new Date(iso));
  } catch {
    return iso;
  }
}

export function formatDateTime(iso) {
  try {
    return new Intl.DateTimeFormat(lang === "fa" ? "fa-IR" : "en-GB", {
      year: "numeric",
      month: "short",
      day: "numeric",
      hour: "2-digit",
      minute: "2-digit",
    }).format(new Date(iso));
  } catch {
    return iso;
  }
}
