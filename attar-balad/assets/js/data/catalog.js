export const getProduct = (id) => products.find((p) => p.id === id);
export const getProductBySlug = (slug) => products.find((p) => p.slug === slug);
export const getCategory = (id) => categories.find((c) => c.id === id);
export const productsInCategory = (id) => products.filter((p) => p.cat === id);

export const priceRange = () => {
  const prices = products.flatMap((p) => p.variants.map((v) => v.price));
  return { min: Math.min(...prices), max: Math.max(...prices) };
};

export const relatedProducts = (product, limit = 4) => {
  const sameCat = products.filter((p) => p.cat === product.cat && p.id !== product.id);
  const rest = products.filter((p) => p.cat !== product.cat && p.id !== product.id);
  return [...sameCat, ...rest].slice(0, limit);
};
